"""Fail-closed manuscript output from the validated HARTH result schema."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
REPO = ROOT.parents[3]
sys.path.insert(0, str(REPO / "src"))
from howhow.episodes.harth.v2.result_schema import ResultSchemaError, validate_result  # noqa: E402

OUTPUT = ROOT / "generated" / "results.tex"
PLACEHOLDER = r"""% Generated by tools/generate_tables.py. Do not edit.
\section{Results Placeholder}
\begin{table}[ht]
\label{tab:results-folds}
\centering
\fbox{\parbox{0.82\linewidth}{\centering\Large UNVERIFIED\\[4pt]\normalsize No validator-approved v2 result artifact was supplied.\\Metrics are intentionally withheld.}}
\end{table}
"""


def validated(data: object) -> bool:
    try:
        validate_result(data)
        return True
    except (ResultSchemaError, TypeError):
        return False


def _tex(value: Any) -> str:
    return str(value).replace("_", "\\_").replace("&", "\\&").replace("%", "\\%")


def _interval(value: Any) -> str:
    return f"[{float(value[0]):.6f}, {float(value[1]):.6f}]"


def _table(label: str, caption: str, columns: str, rows: list[str]) -> str:
    return (
        "\\begin{table}[ht]\n\\centering\n"
        f"\\caption{{{caption}}}\n\\label{{{label}}}\n"
        f"\\begin{{tabular}}{{{columns}}}\n\\toprule\n"
        + "\n"
        + "\\midrule\n".join(["", *rows])
        + "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n"
    )


def latex(data: dict[str, object]) -> str:
    result = validate_result(data)
    analysis = result["analysis"]
    classes = result["class_vocabulary"]
    rows: list[str] = []
    for fold in result["folds"]:
        state = fold["states"]["calibrated"]
        metrics = state["metrics"]
        uncertainty = state["uncertainty"]
        support = state["class_support"]
        support_text = ", ".join(f"{name}:{support[name]}" for name in classes)
        rows.append(
            f"{_tex(fold['fold_id'])} & {metrics['nll']:.6f} & {_interval(uncertainty['nll'])} & "
            f"{metrics['brier']:.6f} ({_interval(uncertainty['brier'])}) & "
            f"{metrics['ece']:.6f} ({_interval(uncertainty['ece'])}) & {_tex(support_text)} \\\\",
        )
    fold_table = _table(
        "tab:results-folds",
        "Calibrated metrics, named NLL/Brier/ECE intervals, and complete class support.",
        "lrrrrp{.32\\linewidth}",
        [
            "Fold & NLL & NLL 95\\% CI & Brier & ECE & Support \\\\ ",
            *rows,
        ],
    )
    bootstrap_rows: list[str] = []
    comparison_rows: list[str] = []
    ablation_rows: list[str] = []
    configurations = analysis["configurations"]
    for configuration in ("full_sensor", "back_only", "thigh_only"):
        report = configurations[configuration]
        for state in ("uncalibrated", "calibrated"):
            for metric, summary in report.get("states", {}).get(state, {}).items():
                bootstrap_rows.append(
                    f"{_tex(f'{configuration}/{state}/{metric}')} & {summary['estimate']:.6f} & "
                    f"{_interval(summary['ci_95pct'])} & {summary['repetitions']} \\\\"
                )
        for key, comparison in report.get("comparisons", {}).items():
            interval = comparison.get("interval", {})
            ci = interval.get("ci_95pct", [0.0, 0.0])
            row = (
                f"{_tex(f'{configuration}/{key}')} & {interval.get('estimate', 0.0):.6f} & "
                f"{_interval(ci)} & {comparison.get('p_value', 1.0):.6f} \\\\"
            )
            comparison_rows.append(row)
            if "-vs-full/" in key:
                ablation_rows.append(row)
    primary_raw = analysis["primary_calibration"].get("raw_p", {})
    primary_adjusted = analysis["primary_calibration"].get("adjusted_p", {})
    paired_rows = [
        f"{_tex(f'full_sensor/calibration/{metric}')} & {primary_raw.get(metric, 1.0):.6f} & "
        f"{primary_adjusted.get(metric, 1.0):.6f} \\\\"
        for metric in ("nll", "brier", "ece")
    ]
    for metric, value in analysis["exploratory_ablation"].get("raw_p", {}).items():
        paired_rows.append(
            f"{_tex(f'ablation/{metric}')} & {value:.6f} & "
            f"{analysis['exploratory_ablation'].get('adjusted_p', {}).get(metric, 1.0):.6f} \\\\"
        )
    diagnostics = analysis["diagnostics"]
    support_rows = [
        f"{_tex(key)} & {count} " + r"\\"
        for key, count in diagnostics.get("window_counts", {}).items()
    ]
    failure_values = list(result.get("failures", [])) + list(diagnostics.get("failures", []))
    failure_rows = [str(failure) for failure in failure_values] or ["none"]
    return (
        "% Generated by tools/generate_tables.py. Do not edit.\n"
        "Values below are copied only after strict schema validation; no metric is hand-entered.\n"
        "\\section{Validated Protocol-v2 Results}\n"
        + fold_table
        + _table(
            "tab:results-bootstrap",
            "Cluster-bootstrap estimates and 95 percent confidence intervals for every configuration and state.",
            "lp{.24\\linewidth}lr",
            ["Population & Estimate [95\\% CI] & Repetitions \\\\ ", *bootstrap_rows],
        )
        + _table(
            "tab:results-paired",
            "Paired effects with raw and Holm-adjusted p values.",
            "lrr",
            ["Comparison & Raw p & Holm p \\\\ ", *paired_rows],
        )
        + _table(
            "tab:results-comparisons",
            "Paired comparison effects and intervals, including all sensor ablations.",
            "lp{.22\\linewidth}lr",
            ["Comparison & Effect [95\\% CI] & p \\\\ ", *comparison_rows],
        )
        + _table(
            "tab:results-ablations",
            "All preregistered sensor-ablation effects and intervals.",
            "lp{.22\\linewidth}lr",
            ["Ablation & Effect [95\\% CI] & p \\\\ ", *ablation_rows],
        )
        + _table(
            "tab:results-diagnostics",
            "Window diagnostics and preserved calibration failures.",
            "lr",
            ["Population & Windows \\\\ ", *support_rows],
        )
        + "\\paragraph{Preserved calibration failures.}\\begin{verbatim}\n"
        + "\n".join(failure_rows)
        + "\\end{verbatim}\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--artifact", type=Path, default=ROOT / "artifacts" / "results-v2.json")
    parser.add_argument("--check-only", action="store_true")
    args = parser.parse_args()
    try:
        data = (
            json.loads(args.artifact.read_text(encoding="utf-8"))
            if args.artifact.is_file()
            else None
        )
    except (OSError, json.JSONDecodeError):
        data = None
    content = latex(data) if isinstance(data, dict) and validated(data) else PLACEHOLDER
    if args.check_only:
        return int(not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != content)
    OUTPUT.write_text(content, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
